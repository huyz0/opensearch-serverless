/// Whether the Java resolves `name` on a scope holding `value`.
pub(super) fn resolves(value: &Val, name: &str) -> bool {
    let names = match value {
        Val::Str(_) => STRING,
        Val::Int(i) if i32::try_from(*i).is_ok() => INTEGER,
        Val::Int(_) => LONG,
        Val::Big(_) => BIG_INTEGER,
        Val::Double(_) => DOUBLE,
        Val::Bool(_) => BOOLEAN,
        Val::Null | Val::List(_) | Val::Map(_) => return false,
    };
    names.contains(&name)
}
